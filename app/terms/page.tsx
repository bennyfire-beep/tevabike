/** Turns a section's plain text into paragraphs, sub-headings and bullet lists. */
function SectionBody({ text }: { text: string }) {
  const lines = text.trim().split("\n").map((l) => l.trim()).filter(Boolean);
  const out: React.ReactNode[] = [];
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (line.startsWith("- ")) {
      const items: string[] = [];
      while (i < lines.length && lines[i].startsWith("- ")) items.push(lines[i++].slice(2));
      i--;
      out.push(
        <ul key={i} className="list-disc pr-5 space-y-1.5">
          {items.map((it) => <li key={it}>{it}</li>)}
        </ul>,
      );
    } else if (line.endsWith(":") && line.length <= 40) {
      out.push(<h3 key={i} className="font-bold pt-2" style={{ color: C.offWhite }}>{line.slice(0, -1)}</h3>);
    } else {
      out.push(<p key={i} className="leading-relaxed">{line}</p>);
    }
  }
  return <div className="space-y-3">{out}</div>;
}

